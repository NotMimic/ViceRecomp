// Physical pages: on the console, 64 KiB frames a title maps into its own
// reservations, at more than one address if it likes. Here each allocation
// is a pagefile-backed section, its pages are 64 KiB slices of it, and a
// mapping is a view of consecutive slices in place of a host placeholder.

const PAGE: usize = 64 << 10;

/// A section, and which of its pages are committed. A section's commit is
/// its own: a page committed through any view of it is committed in every
/// view, those mapped later too, and stays so (the pages of a
/// `SEC_RESERVE` section cannot be decommitted).
struct Section(HANDLE, Box<[AtomicU64]>);

// SAFETY: a section handle may be used from any thread.
unsafe impl Send for Section {}
// SAFETY: as above.
unsafe impl Sync for Section {}

impl Drop for Section {
    fn drop(&mut self) {
        // SAFETY: our handle; views keep the section alive on their own.
        unsafe { CloseHandle(self.0) };
    }
}

impl Section {
    /// A section of `pages` pages, none of them committed yet.
    fn new(handle: HANDLE, pages: usize) -> Self {
        Self(handle, (0..pages.div_ceil(64)).map(|_| AtomicU64::new(0)).collect())
    }

    /// Whether pages `[first, first + n)` were committed ([`commit`]).
    fn committed(&self, first: usize, n: usize) -> bool {
        (first..first + n).all(|page| {
            self.1
                .get(page / 64)
                .is_some_and(|word| word.load(Ordering::Acquire) & (1u64 << (page % 64)) != 0)
        })
    }

    /// Pages `[first, first + n)` are committed.
    fn note_committed(&self, first: usize, n: usize) {
        for page in first..first + n {
            if let Some(word) = self.1.get(page / 64) {
                word.fetch_or(1u64 << (page % 64), Ordering::Release);
            }
        }
    }
}

/// Where a page lives, or what a view starts with: a section and a page
/// index in it.
#[derive(Clone)]
struct Slice {
    section: Arc<Section>,
    index: usize,
}

impl Slice {
    /// The key in `Physical::shown` of the page `k` pages after this one.
    fn key(&self, k: usize) -> (usize, usize) {
        (Arc::as_ptr(&self.section) as usize, self.index + k)
    }
}

#[derive(Default)]
struct Physical {
    next_page: usize,
    /// Freed page numbers available for reuse, keeping every live page number
    /// inside the title's 21-bit `number >> 4` field across long sessions.
    free_pages: VecDeque<usize>,
    pages: HashMap<usize, Slice>,
    /// Where each page shows: by its section and its index there, the
    /// address of that page in every view that shows it now ([`shown_at`];
    /// as upstream's c75fdba keeps it). The title maps pages where the
    /// card reads them and has them filled afterwards by DirectStorage,
    /// which writes through views of our own.
    shown: HashMap<(usize, usize), Vec<usize>>,
}

impl Physical {
    /// Reserves `n` distinct page numbers below `PAGE_NUMBER_LIMIT`, reusing
    /// freed numbers first and bumping `next_page` for the remainder.
    /// Returns `None` without mutating state if fewer than `n` numbers remain.
    fn take_page_numbers(&mut self, n: usize) -> Option<Vec<usize>> {
        let from_free = self.free_pages.len().min(n);
        let from_bump = n - from_free;
        let bump_frames = from_bump.checked_mul(FRAMES)?;
        let new_next = self.next_page.checked_add(bump_frames)?;
        if new_next > PAGE_NUMBER_LIMIT {
            return None;
        }
        let mut out = Vec::with_capacity(n);
        for _ in 0..from_free {
            out.push(self.free_pages.pop_front()?);
        }
        let first = self.next_page;
        self.next_page = new_next;
        for i in 0..from_bump {
            out.push(first + i * FRAMES);
        }
        Some(out)
    }

    /// Removes `number` from `pages` and recycles it only if it was live so
    /// duplicate or unknown frees can never hand out the same number twice.
    fn release_page(&mut self, number: usize) -> bool {
        if self.pages.remove(&number).is_some() {
            self.free_pages.push_back(number);
            true
        } else {
            false
        }
    }
}

static PHYSICAL: LazyLock<Mutex<Physical>> = LazyLock::new(|| {
    Mutex::new(Physical {
        // Page numbers are opaque to titles; 0 stays unused.
        next_page: 0x10_0000,
        ..Default::default()
    })
});

fn physical() -> MutexGuard<'static, Physical> {
    PHYSICAL.lock().unwrap_or_else(|e| e.into_inner())
}

/// What only remaps look at and change, apart from the page table
/// ([`physical`]), so that DirectStorage's lookups there ([`runs`],
/// [`shown_at`]) need not wait for a remap's kernel calls
/// ([`remap_unlocked`]). Remaps run one after another on it, as they did
/// on the page table.
struct Mapped {
    /// Mapped views by address: their length and what they show.
    views: BTreeMap<usize, (usize, Slice)>,
    /// Placeholders our own unmaps left, by address: their length, which
    /// is the unmapped view's ([`map`] splits nothing there). Notes only:
    /// a call we do not see may have changed the range since, and a map
    /// that finds so splits as without them ([`remap_calls`]).
    placeholders: BTreeMap<usize, usize>,
}

static MAPPED: Mutex<Mapped> = Mutex::new(Mapped {
    views: BTreeMap::new(),
    placeholders: BTreeMap::new(),
});

fn mapped() -> MutexGuard<'static, Mapped> {
    MAPPED.lock().unwrap_or_else(|e| e.into_inner())
}

/// `VICTORY_REMAP_UNLOCKED`: whether a remap takes the page table only for
/// each look and change, never across a kernel call, so DirectStorage's
/// lookups there no longer wait for a remap's map and unmap calls. `0`: a
/// remap holds it from start to end, as before.
fn remap_unlocked() -> bool {
    static ON: LazyLock<bool> =
        LazyLock::new(|| std::env::var_os("VICTORY_REMAP_UNLOCKED").is_none_or(|v| v != "0"));
    *ON
}

/// Remaps under way, for the frame log's count of page-table lookups that
/// ran meanwhile.
static REMAPPING: AtomicUsize = AtomicUsize::new(0);

/// The page table as a remap has it: held from start to end, or taken for
/// each look and change only ([`remap_unlocked`]).
///
/// Letting go keeps what the page table answers true. Remaps never change
/// `pages`. Each change to `shown` is made whole under the lock. A view's
/// pages enter `shown` before the GPU side hears that the range is new
/// ([`map`]), so a write a lookup misses there happened before the GPU
/// side forgets what it holds of the range. They leave `shown` before the
/// view is unmapped ([`unmap`]), so a write a lookup misses there is one
/// it missed with the lock held as well: the lookup waited until the view
/// was gone.
enum Table {
    Held(MutexGuard<'static, Physical>),
    Brief,
}

impl Table {
    fn with<R>(&mut self, f: impl FnOnce(&mut Physical) -> R) -> R {
        match self {
            Table::Held(held) => f(&mut **held),
            Table::Brief => f(&mut *physical()),
        }
    }
}

/// A remap from start to end: what only remaps change, and the page table
/// as [`Table`] has it.
struct Remap {
    mapped: MutexGuard<'static, Mapped>,
    table: Table,
}

impl Remap {
    fn begin() -> Self {
        let mapped = mapped();
        REMAPPING.fetch_add(1, Ordering::Relaxed);
        let table = if remap_unlocked() {
            victory_gpu::framelog::add(victory_gpu::framelog::T::RemapsUnlocked, 1);
            Table::Brief
        } else {
            Table::Held(physical())
        };
        Self { mapped, table }
    }
}

impl Drop for Remap {
    fn drop(&mut self) {
        REMAPPING.fetch_sub(1, Ordering::Relaxed);
    }
}

/// The page table for one of DirectStorage's lookups ([`runs`],
/// [`shown_at`]). The frame log gets the wait to take it, and whether a
/// remap was under way meanwhile.
fn looked_up() -> MutexGuard<'static, Physical> {
    use victory_gpu::framelog::{T, add};
    let asked = std::time::Instant::now();
    let table = physical();
    add(T::PageTableWaitNs, asked.elapsed().as_nanos() as u64);
    add(T::PageTableLookups, 1);
    if REMAPPING.load(Ordering::Relaxed) > 0 {
        add(T::PageLookupsInRemap, 1);
    }
    table
}

/// `count` is in and out (pages wanted, pages given); all or nothing here.
pub extern "system" fn XMemAllocatePhysicalPages(
    flags: u64,
    count: *mut usize,
    pages: *mut usize,
) -> BOOL {
    if count.is_null() || pages.is_null() {
        return 0;
    }
    // SAFETY: checked non-null.
    let n = unsafe { *count };
    let Some(size) = n.checked_mul(PAGE).filter(|&s| s > 0) else {
        return 0;
    };
    // A pagefile-backed section of `size` bytes, its pages committed when
    // first mapped or written (`commit`): the title asks for 6.1
    // GiB at once, which a busy host often cannot commit (error 1450).
    // SAFETY: plain section creation.
    let handle = unsafe {
        CreateFileMappingW(
            INVALID_HANDLE_VALUE,
            std::ptr::null(),
            // Under Wine a committed section is a sparse file, free until
            // touched, and committing a reserved one page by page costs a
            // wineserver request each that scans every range committed so
            // far: commit it whole there.
            PAGE_READWRITE | if on_wine() { SEC_COMMIT } else { SEC_RESERVE },
            (size as u64 >> 32) as u32,
            size as u32,
            std::ptr::null(),
        )
    };
    if handle.is_null() {
        let error = std::io::Error::last_os_error();
        tracing::warn!(n, %error, "XMemAllocatePhysicalPages failed");
        // SAFETY: checked non-null.
        unsafe { count.write(0) };
        return 0;
    }
    tracing::debug!(
        n,
        flags = format_args!("{flags:#x}"),
        "XMemAllocatePhysicalPages"
    );
    let section = Arc::new(Section::new(handle, n));
    let mut physical = physical();
    let Some(numbers) = physical.take_page_numbers(n) else {
        drop(physical);
        tracing::warn!(n, "XMemAllocatePhysicalPages: 21-bit page number space exhausted");
        // SAFETY: checked non-null.
        unsafe { count.write(0) };
        return 0;
    };
    for (index, number) in numbers.into_iter().enumerate() {
        let slice = Slice {
            section: section.clone(),
            index,
        };
        physical.pages.insert(number, slice);
        // SAFETY: the title passes room for `n` page numbers.
        unsafe { pages.add(index).write(number) };
    }
    drop(physical);
    // For the GPU side's in-place census: only a committed section can be
    // opened as a host heap. Keep `section` alive for the call.
    victory_gpu::title_memory_section(handle as usize, size as u64, on_wine());
    let _ = section;
    1
}

/// Page numbers count 4 KiB frames, so a 64 KiB page's is a multiple of
/// 16: the title keeps them as 21-bit `number >> 4` and rebuilds
/// them with `<< 4` (128 GiB of pages at most).
const FRAMES: usize = PAGE >> 12;
/// Exclusive upper bound on page numbers that survive the title's 21-bit
/// `number >> 4` / `<< 4` round-trip (`0x200_0000`, max `0x1ff_fff0`).
const PAGE_NUMBER_LIMIT: usize = (1usize << 21) * FRAMES;

/// Pages still mapped stay readable through their views until unmapped.
pub extern "system" fn XMemFreePhysicalPages(n: usize, pages: *const usize) -> BOOL {
    if pages.is_null() {
        return 0;
    }
    let mut physical = physical();
    for i in 0..n {
        // SAFETY: the title passes `n` page numbers.
        physical.release_page(unsafe { *pages.add(i) });
    }
    1
}

/// A view of our own on consecutive slices of one section, committed and
/// writable, unmapped when dropped.
struct View {
    at: MEMORY_MAPPED_VIEW_ADDRESS,
    len: usize,
}

impl View {
    /// Maps `n` slices from `slice` on.
    fn map(slice: &Slice, n: usize) -> Option<View> {
        use windows_sys::Win32::System::Memory::{FILE_MAP_WRITE, MapViewOfFile};
        let (offset, len) = ((slice.index * PAGE) as u64, n * PAGE);
        // SAFETY: slices of a section we own; the view is ours until dropped.
        let at = unsafe {
            MapViewOfFile(
                slice.section.0,
                FILE_MAP_WRITE,
                (offset >> 32) as u32,
                offset as u32,
                len,
            )
        };
        if at.Value.is_null() {
            return None;
        }
        let view = View { at, len };
        if !commit(at.Value as usize, len) {
            return None;
        }
        slice.section.note_committed(slice.index, n);
        Some(view)
    }

    fn bytes(&mut self) -> &mut [u8] {
        // SAFETY: the view holds `len` committed read-write bytes, ours
        // alone while `self` lives (other views of the slices only alias
        // them, as the console's do).
        unsafe { std::slice::from_raw_parts_mut(self.at.Value.cast(), self.len) }
    }
}

impl Drop for View {
    fn drop(&mut self) {
        use windows_sys::Win32::System::Memory::UnmapViewOfFile;
        // SAFETY: our view.
        unsafe { UnmapViewOfFile(self.at) };
    }
}

/// The pages behind bytes `[offset, offset + len)` of `pages` (64 KiB
/// each), as runs of consecutive slices of one section: each run's first
/// slice and its length in pages. One look at the page table, which the
/// title's own mapping calls share with every DirectStorage worker. `None`
/// if a page is unknown or `pages` ends early.
fn runs(pages: &[usize], offset: usize, len: usize) -> Option<Vec<(Slice, usize)>> {
    let end = offset.checked_add(len)?;
    let pages = pages.get(offset / PAGE..end.div_ceil(PAGE))?;
    let physical = looked_up();
    let mut runs: Vec<(Slice, usize)> = Vec::new();
    for page in pages {
        let slice = physical.pages.get(page)?;
        match runs.last_mut() {
            Some((first, n))
                if Arc::ptr_eq(&first.section, &slice.section)
                    && slice.index == first.index + *n =>
            {
                *n += 1;
            }
            _ => runs.push((slice.clone(), 1)),
        }
    }
    Some(runs)
}

/// Whether every page under `[offset, offset + len)` is known (a write that
/// fails with them known is a host failure).
pub(crate) fn pages_known(pages: &[usize], offset: usize, len: usize) -> bool {
    runs(pages, offset, len).is_some()
}

/// Copies `data` into physical pages, from `offset` bytes into the first,
/// whether or not they are mapped anywhere (DirectStorage destinations).
/// One view per run of consecutive pages, not one per page: each view
/// costs a map, a commit and an unmap (which flushes every core's TLB).
/// False if a page is unknown or the host fails.
pub(crate) fn write_physical(pages: &[usize], offset: usize, data: &[u8]) -> bool {
    let Some(runs) = runs(pages, offset, data.len()) else {
        return false;
    };
    let (mut within, mut done) = (offset % PAGE, 0);
    for (slice, n) in &runs {
        let Some(mut view) = View::map(slice, *n) else {
            return false;
        };
        let k = (n * PAGE - within).min(data.len() - done);
        view.bytes()[within..within + k].copy_from_slice(&data[done..done + k]);
        (within, done) = (0, done + k);
    }
    true
}

/// Bytes `[offset, offset + len)` of physical pages, writable in place
/// until dropped: DirectStorage decodes into it instead of a buffer it
/// would then copy.
pub(crate) struct PageWindow {
    view: View,
    within: usize,
    len: usize,
}

impl PageWindow {
    pub(crate) fn bytes(&mut self) -> &mut [u8] {
        let (within, len) = (self.within, self.len);
        &mut self.view.bytes()[within..within + len]
    }
}

/// A window on bytes `[offset, offset + len)` of `pages` when they are
/// consecutive pages of one allocation (how titles usually hand them out);
/// `None` otherwise (pages of several allocations, out of order, or
/// unknown, or a host failure), which `write_physical` then handles or
/// reports.
pub(crate) fn page_window(pages: &[usize], offset: usize, len: usize) -> Option<PageWindow> {
    let runs = runs(pages, offset, len)?;
    let [(slice, n)] = runs.as_slice() else {
        return None;
    };
    Some(PageWindow {
        view: View::map(slice, *n)?,
        within: offset % PAGE,
        len,
    })
}

/// The title addresses that show bytes `[offset, offset + len)` of `pages`
/// now, byte for byte, as runs (address, bytes) in address order: a write
/// to the pages through a view of our own ([`page_window`],
/// [`write_physical`]) lands there too, and nothing that watches those
/// addresses sees it (the GPU side's guards fault only on a write at the
/// guarded address itself). Empty if no view shows them. Byte for byte,
/// not by whole pages: the title packs several small textures into one
/// page and fills each with a request of its own.
pub(crate) fn shown_at(pages: &[usize], offset: usize, len: usize) -> Vec<(usize, usize)> {
    let Some(end) = offset.checked_add(len) else {
        return Vec::new();
    };
    let first = offset / PAGE;
    let Some(touched) = pages.get(first..end.div_ceil(PAGE)) else {
        return Vec::new();
    };
    let mut pieces: Vec<(usize, usize)> = Vec::new();
    {
        let physical = looked_up();
        for (i, page) in touched.iter().enumerate() {
            let Some(addresses) = physical.pages.get(page).and_then(|slice| physical.shown.get(&slice.key(0))) else {
                continue;
            };
            // The bytes of this page that the write covers.
            let lo = if i == 0 { offset % PAGE } else { 0 };
            let hi = (end - (first + i) * PAGE).min(PAGE);
            pieces.extend(addresses.iter().map(|&at| (at + lo, hi - lo)));
        }
    }
    pieces.sort_unstable();
    let mut runs: Vec<(usize, usize)> = Vec::new();
    for (at, bytes) in pieces {
        match runs.last_mut() {
            Some((start, n)) if *start + *n == at => *n += bytes,
            _ => runs.push((at, bytes)),
        }
    }
    runs
}

/// Bytes `[offset, offset + len)` of `pages` have been written through a
/// view of our own: the GPU side is told at every title address that
/// shows them (`victory_gpu::title_memory_written`; what it does with it
/// is `VICTORY_PAGE_WRITES`' to say, and it counts either way). Call when
/// the bytes are there, and without the page table's lock ([`shown_at`]
/// takes and leaves it).
pub(crate) fn pages_written(pages: &[usize], offset: usize, len: usize) {
    for (at, bytes) in shown_at(pages, offset, len) {
        victory_gpu::title_memory_written(at, bytes, true);
    }
}

/// Maps `n` pages at `address`, in place of what is mapped there; null
/// `pages` unmaps. Returns `address`, or null if a page or the host fails.
pub extern "system" fn XMemMapPhysicalPages(
    address: *mut c_void,
    n: usize,
    pages: *const usize,
) -> *mut c_void {
    let base = address as usize;
    let mut r = Remap::begin();
    // Until the pages are mapped again: `unmap` takes whole views away and
    // maps what stays of them again, and a mapped view is a reservation
    // until it is committed. A read of title memory in place must not fall
    // into that gap (`victory_gpu::title_memory_remapping`).
    let _changing = victory_gpu::title_memory_remapping();
    unmap(&mut r, base, n * PAGE);
    if pages.is_null() {
        return address;
    }
    // SAFETY: the title passes `n` page numbers.
    let pages = unsafe { std::slice::from_raw_parts(pages, n) };
    // What the pages are, in one look at the page table.
    let slices = r.table.with(|table| pages.iter().map(|page| table.pages.get(page).cloned()).collect::<Vec<_>>());
    let mut i = 0;
    while i < n {
        let Some(first) = slices[i].clone() else {
            tracing::warn!(page = pages[i], "XMemMapPhysicalPages: unknown page");
            return std::ptr::null_mut();
        };
        // One view per run of consecutive slices of one section.
        let run = 1 + slices[i + 1..]
            .iter()
            .zip(1..)
            .take_while(|&(slice, k)| {
                slice.as_ref().is_some_and(|s| {
                    Arc::ptr_eq(&s.section, &first.section) && s.index == first.index + k
                })
            })
            .count();
        if !map(&mut r, base + i * PAGE, run * PAGE, first) {
            return std::ptr::null_mut();
        }
        i += run;
    }
    address
}

/// One page at each address; null `pages`, or a page number 0, unmaps
/// (the title passes 0 for addresses to clear).
pub extern "system" fn XMemMapPhysicalPagesScatter(
    addresses: *const *mut c_void,
    n: usize,
    pages: *const usize,
) -> BOOL {
    if addresses.is_null() {
        return 0;
    }
    for i in 0..n {
        // SAFETY: the title passes `n` addresses and, unless null, `n` pages.
        let (address, page) = unsafe {
            (
                *addresses.add(i),
                if pages.is_null() || *pages.add(i) == 0 {
                    std::ptr::null()
                } else {
                    pages.add(i)
                },
            )
        };
        if XMemMapPhysicalPages(address, 1, page).is_null() {
            return 0;
        }
    }
    1
}

/// Maps the physical pages shown at `[from, from + len)` at `to` as well,
/// in place of what `to` shows; `from` 0 unmaps. The GPU's page-mapping
/// copies (`victory_gpu`, queue `CopyPageMappingsBatchX`):
/// the title maps pages into a pool view, then has the GPU map them into its tiled
/// heap. Page by page; false if a source page is not mapped physical memory.
pub fn map_alias(to: u64, from: u64, len: u64) -> bool {
    let (to, from, len) = (to as usize, from as usize, len as usize);
    let mut r = Remap::begin();
    // As in `XMemMapPhysicalPages`: no read in place meets the gap.
    let _changing = victory_gpu::title_memory_remapping();
    unmap(&mut r, to, len);
    for k in (0..len).step_by(PAGE) {
        if from == 0 {
            break;
        }
        let at = from + k;
        let Some(slice) = r
            .mapped
            .views
            .range(..=at)
            .next_back()
            .filter(|(base, (size, _))| at < *base + size)
            .map(|(base, (_, s))| Slice {
                index: s.index + (at - base) / PAGE,
                section: s.section.clone(),
            })
        else {
            return false;
        };
        if !map(&mut r, to + k, PAGE, slice) {
            return false;
        }
    }
    true
}

/// Runs kernel calls of a remap (`calls` of them) and adds their time to
/// the frame log's remapping part (`victory_gpu::framelog`).
fn kernel<R>(calls: u64, call: impl FnOnce() -> R) -> R {
    use victory_gpu::framelog::{T, add};
    let at = std::time::Instant::now();
    let r = call();
    add(T::RemapKernelNs, at.elapsed().as_nanos() as u64);
    add(T::RemapKernelCalls, calls);
    r
}

/// Runs the GPU side's notes of a remap and adds their time to the frame
/// log's remapping part.
fn noting(note: impl FnOnce()) {
    use victory_gpu::framelog::{T, add};
    let at = std::time::Instant::now();
    note();
    add(T::RemapNoteNs, at.elapsed().as_nanos() as u64);
}

/// `VICTORY_REMAP_CALLS`: whether a remap leaves out the kernel calls that
/// would change nothing: the placeholder split where our own unmap left
/// that placeholder exactly ([`Physical::placeholders`]), and the commit
/// of section pages committed already ([`Section::committed`]). `0`: every
/// map splits and commits, as before.
fn remap_calls() -> bool {
    static ON: LazyLock<bool> =
        LazyLock::new(|| std::env::var_os("VICTORY_REMAP_CALLS").is_none_or(|v| v != "0"));
    *ON
}

/// Notes of placeholders kept at most ([`Physical::placeholders`]); past
/// it they are all forgotten.
const PLACEHOLDERS_MOST: usize = 1 << 18;

/// Kernel calls a remap left out ([`remap_calls`]), for the frame log.
fn saved(calls: u64) {
    victory_gpu::framelog::add(victory_gpu::framelog::T::RemapCallsSaved, calls);
}

/// Splits `[base, base + len)` out of the placeholder around it (failing
/// harmlessly when the range is the whole placeholder). With `noted`, the
/// note of the placeholder it was split out of gives way to notes of the
/// parts left on either side.
fn split(mapped: &mut Mapped, base: usize, len: usize, noted: bool) {
    // SAFETY: acts only on placeholders.
    let split = kernel(1, || unsafe {
        VirtualFree(base as *mut c_void, len, MEM_RELEASE | MEM_PRESERVE_PLACEHOLDER)
    }) != 0;
    let end = base + len;
    let around = mapped.placeholders.range(..=base).next_back().map(|(&at, &size)| (at, size));
    if let Some((at, size)) = around
        && noted
        && at + size > base
    {
        mapped.placeholders.remove(&at);
        if split && at + size >= end {
            if at < base {
                mapped.placeholders.insert(at, base - at);
            }
            if at + size > end {
                mapped.placeholders.insert(end, at + size - end);
            }
        }
    }
}

/// Maps `len` bytes of `slice`'s section from its page on in place of the
/// placeholder at `base`, which must be that range exactly.
fn map_view(slice: &Slice, base: usize, len: usize) -> MEMORY_MAPPED_VIEW_ADDRESS {
    // SAFETY: replaces a placeholder only; the section is ours.
    unsafe {
        MapViewOfFile3(
            slice.section.0,
            GetCurrentProcess(),
            base as *const c_void,
            (slice.index * PAGE) as u64,
            len,
            MEM_REPLACE_PLACEHOLDER,
            PAGE_READWRITE,
            std::ptr::null_mut(),
            0,
        )
    }
}

/// Maps `slice` and the slices after it over `[base, base + len)`, which
/// must lie in one placeholder.
fn map(r: &mut Remap, base: usize, len: usize, slice: Slice) -> bool {
    let leave_out = remap_calls();
    // Where our own unmap left this very placeholder there is nothing to
    // split.
    let exact = leave_out && r.mapped.placeholders.get(&base) == Some(&len);
    if !exact {
        split(&mut r.mapped, base, len, leave_out);
    }
    let mut view = kernel(1, || map_view(&slice, base, len));
    if exact && view.Value as usize == base {
        saved(1);
    } else if exact {
        // A call we do not see changed the range since: split as without
        // the note, and map again.
        r.mapped.placeholders.remove(&base);
        split(&mut r.mapped, base, len, leave_out);
        view = kernel(1, || map_view(&slice, base, len));
    }
    // The placeholder there is taken, or what is there is not known.
    r.mapped.placeholders.remove(&base);
    if view.Value as usize != base {
        tracing::warn!(
            address = format_args!("{base:#x}"),
            len,
            error = %std::io::Error::last_os_error(),
            "mapping physical pages failed (not a placeholder?)"
        );
        return false;
    }
    let pages = len.div_ceil(PAGE);
    let committed = if leave_out && slice.section.committed(slice.index, pages) {
        saved(1);
        true
    } else {
        let done = kernel(1, || commit(base, len));
        if done {
            slice.section.note_committed(slice.index, pages);
        }
        done
    };
    if !committed {
        // SAFETY: the view just mapped, back to a placeholder.
        kernel(1, || unsafe { UnmapViewOfFile2(GetCurrentProcess(), view, MEM_PRESERVE_PLACEHOLDER) });
        return false;
    }
    // Where the pages show, before the GPU side hears of the range
    // ([`Table`]).
    r.table.with(|table| {
        for k in 0..len.div_ceil(PAGE) {
            table.shown.entry(slice.key(k)).or_default().push(base + k * PAGE);
        }
    });
    noting(|| {
        // New contents, read-write: the GPU side's copies no longer guard it.
        victory_gpu::title_memory_remapped(base, len);
        // What the range shows now, for the GPU side's in-place census.
        victory_gpu::title_memory_view(base, len, slice.section.0 as usize, (slice.index * PAGE) as u64);
    });
    r.mapped.views.insert(base, (len, slice));
    true
}

/// Commits the section pages a view shows (once per page, whichever view).
fn commit(base: usize, len: usize) -> bool {
    if on_wine() {
        return true; // sections are committed whole there
    }
    // SAFETY: `[base, base + len)` is a view of a reserved section.
    if !unsafe { VirtualAlloc(base as *const c_void, len, MEM_COMMIT, PAGE_READWRITE) }.is_null() {
        return true;
    }
    let error = std::io::Error::last_os_error();
    if error.raw_os_error() == Some(ERROR_COMMITMENT_LIMIT as i32) {
        let mut info = PERFORMANCE_INFORMATION {
            cb: size_of::<PERFORMANCE_INFORMATION>() as u32,
            ..Default::default()
        };
        // SAFETY: the buffer and size describe a writable PERFORMANCE_INFORMATION.
        let queried = unsafe { K32GetPerformanceInfo(&mut info, info.cb) } != 0;
        victory_loader::log_crash(&commit_limit_message(len, &error, queried.then_some(&info)));
    } else {
        tracing::warn!(len, %error, "committing physical pages failed");
    }
    false
}

fn commit_limit_message(
    len: usize,
    error: &std::io::Error,
    info: Option<&PERFORMANCE_INFORMATION>,
) -> String {
    let mut message = format!(
        "VIctory: Windows commit limit reached while committing {len} bytes of physical pages: {error}.\n"
    );
    if let Some(info) = info {
        use std::fmt::Write;

        let committed = info.CommitTotal * info.PageSize / MIB;
        let limit = info.CommitLimit * info.PageSize / MIB;
        let _ = writeln!(
            message,
            "System commit: {committed} MiB of {limit} MiB in use."
        );
    }
    message.push_str(
        "Close other applications or increase the Windows paging file size, then retry.\n",
    );
    message
}

/// Returns `[base, base + len)` to placeholders; views reaching past it
/// are mapped again outside it.
fn unmap(r: &mut Remap, base: usize, len: usize) {
    // No bytes: no view to return. The search below would still find the
    // view holding `base` and cut it in two there, and its range of views
    // starting inside would run backwards (which `BTreeMap` panics on).
    if len == 0 {
        return;
    }
    let end = base + len;
    // Views do not overlap: the one holding `base`, then those starting
    // inside (the GPU's page mappings make one view per page).
    let first = r
        .mapped
        .views
        .range(..=base)
        .next_back()
        .filter(|(at, (size, _))| *at + size > base)
        .map(|(at, _)| *at);
    let hit: Vec<usize> = first
        .into_iter()
        .chain(r.mapped.views.range(base + 1..end).map(|(at, _)| *at))
        .collect();
    for at in hit {
        let Some((size, slice)) = r.mapped.views.remove(&at) else {
            continue;
        };
        // Out of `shown` before the view goes ([`Table`]).
        r.table.with(|table| {
            for k in 0..size.div_ceil(PAGE) {
                let key = slice.key(k);
                if let Some(addresses) = table.shown.get_mut(&key) {
                    addresses.retain(|&a| a != at + k * PAGE);
                    if addresses.is_empty() {
                        table.shown.remove(&key);
                    }
                }
            }
        });
        noting(|| victory_gpu::title_memory_remapped(at, size));
        // SAFETY: a view we mapped; it becomes a placeholder again.
        let freed = kernel(1, || unsafe {
            UnmapViewOfFile2(
                GetCurrentProcess(),
                MEMORY_MAPPED_VIEW_ADDRESS {
                    Value: at as *mut c_void,
                },
                MEM_PRESERVE_PLACEHOLDER,
            )
        }) != 0;
        if freed && remap_calls() {
            // The placeholder left is the view's range exactly (placeholders
            // join only when asked to).
            if r.mapped.placeholders.len() >= PLACEHOLDERS_MOST {
                r.mapped.placeholders.clear();
            }
            r.mapped.placeholders.insert(at, size);
        }
        if at < base {
            map(r, at, base - at, slice.clone());
        }
        if at + size > end {
            let index = slice.index + (end - at) / PAGE;
            map(r, end, at + size - end, Slice { index, ..slice });
        }
    }
}

/// The oldest layout we know; newer titles pass other flag values (Minecraft
/// 0x20000001) and read the same leading fields.
#[repr(C)]
#[derive(Debug, Default)]
pub struct WorkingSet {
    pub title_limit: usize,
    pub title_used: usize,
    pub tools_limit: usize,
    pub tools_used: usize,
    pub stack_used: u32,
    pub physical_pages: u32,
    pub gpu_optimal_limit: usize,
    pub gpu_optimal_used: usize,
    pub tools_gpu_optimal_limit: usize,
    pub tools_gpu_optimal_used: usize,
    pub kernel_pool_used: u32,
    pub kernel_pool_limit: u32,
}

/// The title's budget and our process's commit as what it uses. No tools
/// memory: a retail console.
// shortcut: all fields are filled whatever the flags ask for, and use is
// not split by bandwidth class (GPU-optimal use reads 0); track
// allocations per class if a title budgets from that field.
pub extern "system" fn XMemGetWorkingSetStatistics(_which: u32, out: *mut WorkingSet) -> BOOL {
    if out.is_null() {
        return 0;
    }
    let mut counters = PROCESS_MEMORY_COUNTERS {
        cb: size_of::<PROCESS_MEMORY_COUNTERS>() as u32,
        ..Default::default()
    };
    // SAFETY: our own process and a sized structure.
    unsafe { K32GetProcessMemoryInfo(GetCurrentProcess(), &mut counters, counters.cb) };
    let (gpu_optimal, standard) = victory_gpu::console::current().title_memory();
    let stats = WorkingSet {
        title_limit: gpu_optimal + standard - TRANSFERRED.load(Ordering::Relaxed),
        title_used: counters.PagefileUsage,
        gpu_optimal_limit: gpu_optimal,
        ..Default::default()
    };
    // What the title is told, logged at the first asking and at every
    // 1,024th: "used" is all the process has committed, the layer's own
    // memory and the card's included (27 GB in run 60's gameplay against a
    // limit of 13.5 GB). A title that budgets its streaming from these two
    // figures believes it is far over its limit.
    // shortcut: the figure is not yet the title's own memory alone (its
    // heaps and the pages it mapped); count those if this line shows the
    // title asking.
    static ASKED: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    let asked = ASKED.fetch_add(1, Ordering::Relaxed);
    if asked.is_multiple_of(1024) {
        tracing::info!(
            asked = asked + 1,
            which = _which,
            limit_mb = stats.title_limit >> 20,
            used_mb = stats.title_used >> 20,
            "the title asks how much memory it uses"
        );
    }
    // SAFETY: checked non-null; the title passes room for the structure.
    unsafe { out.write(stats) };
    1
}

/// Hands title memory (standard, in 2 MiB pages) to the system. The other
/// transfers involve tools memory, which a retail console has none of.
pub extern "system" fn XMemTransferMemory(kind: u32, size: usize) -> BOOL {
    const TITLE_TO_SYSTEM: u32 = 0;
    tracing::info!(kind, size, "XMemTransferMemory");
    if size == 0 {
        return 1;
    }
    let Some(size) = size.checked_next_multiple_of(2 * MIB) else {
        return 0;
    };
    let standard = victory_gpu::console::current().title_memory().1;
    let moved = kind == TITLE_TO_SYSTEM
        && TRANSFERRED
            .fetch_update(Ordering::Relaxed, Ordering::Relaxed, |t| {
                t.checked_add(size).filter(|&t| t <= standard)
            })
            .is_ok();
    moved.into()
}

